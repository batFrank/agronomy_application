<?php

declare(strict_types=1);

namespace App\Tests\Infrastructure\AI\Agent;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Finder\Finder;

/**
 * NoNetworkHttpClientTrap only sees the HTTP clients the container builds. A transport created outside it does
 * not go through the trap: the case that was measured is the SDK platform factory without a client,
 * which ends in the default HTTP client factory, out of the container. Cutting the network of the
 * test process is not an option (the functional tests talk to PostgreSQL), so the guarantee is
 * narrower and is held here: the project code (src, tests, config) never builds a platform or an
 * HTTP transport by hand. Nobody does today; this test makes adding one fail loudly instead of
 * silently opening a way to the provider.
 *
 * If a case is legitimate, build the client in the container (so the trap sees it) or discuss
 * the rule: do not exclude the file.
 */
class NoProviderOutsideTheContainerTest extends TestCase
{
    /**
     * @return \Generator<string, array{string, string}>
     */
    public static function forbiddenConstructionProvider(): \Generator
    {
        yield 'SDK platform factory' => ['/\bcreatePlatform\s*\(/', self::example('$platform = Factory::create#Platform($key);')];
        yield 'default HTTP client factory' => ['/\bHttpClient::create\w*\s*\(/', self::example('$client = Http#Client::create();')];
        yield 'HTTP transport built by hand' => ['/\bnew\s+(?!\\\\?(?:[\w\\\\]*\\\\)?MockHttpClient\b)[\w\\\\]*HttpClient\s*\(/', self::example('$client = new Curl#HttpClient();')];
        yield 'SDK bridge factory import' => ['/Platform\\\\Bridge\\\\\w+\\\\Factory\b/', self::example('use Symfony\AI\Platform\Bridge\#OpenRouter\Factory;')];
        yield 'raw network functions' => ['/\b(?:curl_init|fsockopen|stream_socket_client)\s*\(/', self::example('$handle = curl_#init($url);')];
    }

    #[DataProvider('forbiddenConstructionProvider')]
    public function testTheProjectCodeDoesNotBuildAProviderTransportOutsideTheContainer(string $pattern, string $example): void
    {
        $offenders = [];
        foreach ($this->projectFiles() as $path => $content) {
            if (1 === preg_match($pattern, $content)) {
                $offenders[] = $path;
            }
        }

        self::assertSame([], $offenders, 'Built outside the container, NoNetworkHttpClientTrap cannot see it: ' . implode(', ', $offenders));
    }

    /**
     * Without this, a typo in a pattern would turn the guard into a test that always passes.
     */
    #[DataProvider('forbiddenConstructionProvider')]
    public function testEachPatternRecognizesWhatItForbids(string $pattern, string $example): void
    {
        self::assertSame(1, preg_match($pattern, $example));
    }

    /**
     * The rule is looked up by name, never by position: reordering or adding a case to the provider
     * must not make this test evaluate another rule and stay green without checking anything.
     */
    public function testAHttpClientDoubleIsNotForbidden(): void
    {
        $pattern = self::patternOf('HTTP transport built by hand');

        self::assertSame(1, preg_match($pattern, self::example('$client = new Curl#HttpClient();')), 'The rule under test must forbid a real transport.');
        self::assertSame(0, preg_match($pattern, self::example('$client = new Mock#HttpClient();')));
        self::assertSame(0, preg_match($pattern, self::example('$client = new \\Symfony\\Component\\HttpClient\\Mock#HttpClient($responses);')));
    }

    public function testLookingUpAnUnknownRuleFailsInsteadOfPassingSilently(): void
    {
        $this->expectException(\LogicException::class);

        self::patternOf('a rule that does not exist');
    }

    private static function patternOf(string $name): string
    {
        foreach (self::forbiddenConstructionProvider() as $key => [$pattern]) {
            if ($key === $name) {
                return $pattern;
            }
        }

        throw new \LogicException(\sprintf('There is no rule called "%s".', $name));
    }

    /**
     * The examples are written with a mask so that this file does not match its own rules.
     */
    private static function example(string $masked): string
    {
        return str_replace('#', '', $masked);
    }

    /**
     * @return \Generator<string, string> content by path, relative to the project
     */
    private function projectFiles(): \Generator
    {
        $root = \dirname(__DIR__, 4);
        $finder = (new Finder())
            ->files()
            ->in([$root . '/src', $root . '/tests', $root . '/config'])
            ->name(['*.php', '*.yaml', '*.yml', '*.xml'])
            // Generated by the framework from its own configuration tree, not written by the project.
            ->notName('reference.php');

        foreach ($finder as $file) {
            yield substr($file->getPathname(), \strlen($root) + 1) => $file->getContents();
        }
    }
}
